#!/usr/bin/env bash
# Idempotent bootstrap: place a Go toolchain + module cache inside the repo
# volume so every container replica sees the same tooling. Regenerates and then
# sources tools/env.sh so the current shell gets the resulting environment.
set -euo pipefail
cd "$(dirname "$0")/.."

repo_root="$PWD"
go_version="${GO_VERSION:-1.26.0}"
tools_dir="$repo_root/.tools"
gopath_dir="$repo_root/.gopath"

if [ ! -x "$tools_dir/go/bin/go" ]; then
	url="https://go.dev/dl/go${go_version}.linux-amd64.tar.gz"
	echo "downloading $url"
	tmp_tgz="$(mktemp)"
	trap 'rm -f "$tmp_tgz"' EXIT
	curl -sSLo "$tmp_tgz" "$url"
	mkdir -p "$tools_dir"
	tar -C "$tools_dir" -xzf "$tmp_tgz"
	if [ ! -x "$tools_dir/go/bin/go" ]; then
		echo "bootstrap: toolchain extraction failed ($tools_dir/go/bin/go missing)" >&2
		exit 1
	fi
fi

mkdir -p "$gopath_dir"

# Generated, not committed: the absolute paths depend on where the repo lives,
# and regenerating on every run keeps the file in sync with the actual install.
# This is what makes the `. tools/env.sh` below safe: the file always exists by
# the time it is sourced.
cat > tools/env.sh <<EOF
# Generated by tools/bootstrap.sh -- do not edit.
export GOROOT="$tools_dir/go"
export GOPATH="$gopath_dir"
export PATH="\$GOROOT/bin:\$GOPATH/bin:\$PATH"
EOF

. tools/env.sh

# Sanity check: a broken toolchain must fail here rather than silently later.
go version >/dev/null
